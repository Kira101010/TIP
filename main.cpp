#include <iostream>
using namespace std;

int main() {
    double X, Y;          // объявляем две переменные с плавающей точкой
    cin >> X >> Y;        // считываем X и Y с клавиатуры (каждое с новой строки)

    double sum = X;       // в первый день сумма равна X
    int day = 1;          // счётчик дней, начинаем с первого

    // for без условия выхода — работаем "пока не сломаем" через break
    for (;;) {                    // бесконечный цикл
        if (sum >= Y) {           // если уже достигли нужной суммы
            break;                // выходим из цикла
        }
        sum = sum * 1.1;          // увеличиваем сумму на 10% (умножаем на 1.1)
        day = day + 1;            // переходим к следующему дню
    }

    cout << day;          // выводим номер дня
    return 0;
}